"""Generate map/objects/_index.md from the cards (ICM A3: generated, never hand-edited).

One line per card: name (and code when it differs), the first source path in
its "## See" section, status and date, and the link. Clusters come from the
card's folder. Universe flags (leftover, ghost) live in map/CONTEXT.md.

Usage:
    python scripts/gen_map_index.py          write the index
    python scripts/gen_map_index.py --check  exit 1 if the index is out of date
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OBJECTS = ROOT / "map" / "objects"
INDEX = OBJECTS / "_index.md"
CLUSTERS = ("domain", "application", "infrastructure", "interfaces", "core", "tools")

HEADER = """# Object index

Generated by `scripts/gen_map_index.py` from each card's frontmatter; do not edit by hand (`make check` fails on drift). One line per card.

Format: name — source — status — card
"""


def _front(text: str) -> dict[str, str]:
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    out: dict[str, str] = {}
    for line in (m.group(1).splitlines() if m else []):
        key, _, value = line.partition(":")
        out[key.strip()] = value.split("#", 1)[0].strip()
    return out


def _see(text: str) -> str:
    m = re.search(r"^## See\n+(.*)$", text, re.M)
    paths = re.findall(r"`([^`]+)`", m.group(1)) if m else []
    return paths[0] if paths else ""


def render() -> str:
    parts = [HEADER]
    for cluster in CLUSTERS:
        cards = sorted((OBJECTS / cluster).glob("*.md")) if (OBJECTS / cluster).is_dir() else []
        if not cards:
            continue
        parts.append(f"\n## {cluster}\n")
        for card in cards:
            text = card.read_text(encoding="utf-8")
            fm = _front(text)
            name, code = fm.get("name", card.stem), fm.get("code", "")
            label = name if not code or code == name else f"{name} ({code})"
            status = fm.get("status", "stub")
            when = f" {fm['verified']}" if fm.get("verified") else ""
            see = _see(text)
            source = f"`{see}`" if see else "(no source)"
            parts.append(
                f"- {label} — {source} — {status}{when} — [card]({cluster}/{card.name})\n"
            )
    return "".join(parts)


def main() -> int:
    new = render()
    if "--check" in sys.argv:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current.replace("\r\n", "\n") != new:
            print("map/objects/_index.md is out of date: run python scripts/gen_map_index.py")
            return 1
        return 0
    INDEX.write_text(new, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
