"""Generate tasks/_index.md from the records' frontmatter (ICM A4: one index, generated).

Records are the Markdown files in tasks/, tasks/plans/, tasks/specs/ and
tasks/audits/. Each carries frontmatter `status` (open, done, superseded,
reference) and `date`; the index lists them grouped by status, open first, so
open work is findable without opening every file. Eval tasks live in
tasks/evals/ and are not records.

Usage:
    python scripts/gen_tasks_index.py          write the index
    python scripts/gen_tasks_index.py --check  exit 1 if the index is out of date
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "tasks"
INDEX = TASKS / "_index.md"
FOLDERS = ("", "plans", "specs", "audits")
STATUSES = ("open", "superseded", "done", "reference")

HEADER = """# tasks/ index

Generated by `scripts/gen_tasks_index.py` from each record's frontmatter; do not edit
by hand (`make check` fails on drift). Benchmark tasks are in `evals/` (see
`evals/CONTEXT.md`).

Format: date — record — note
"""


def _front(text: str) -> dict[str, str]:
    m = re.match(r"---\n(.*?)\n---\n", text.replace("\r\n", "\n"), re.S)
    out: dict[str, str] = {}
    for line in (m.group(1).splitlines() if m else []):
        key, _, value = line.partition(":")
        out[key.strip()] = value.strip()
    return out


def _title(text: str, fallback: str) -> str:
    m = re.search(r"^#\s+(.+)$", text, re.M)
    return m.group(1).strip() if m else fallback


def records() -> list[tuple[str, str, str, str, str]]:
    """(status, date, relative path, title, note) per record."""
    rows = []
    for folder in FOLDERS:
        for path in sorted((TASKS / folder).glob("*.md"), key=lambda p: p.name.lower()):
            if path == INDEX:
                continue
            text = path.read_text(encoding="utf-8")
            fm = _front(text)
            rel = path.relative_to(TASKS).as_posix()
            rows.append((fm.get("status", "unknown"), fm.get("date", ""), rel,
                         _title(text, path.stem), fm.get("note", "")))
    return rows


def render(rows: list[tuple[str, str, str, str, str]] | None = None) -> str:
    rows = records() if rows is None else rows
    parts = [HEADER]
    for status in STATUSES:
        group = sorted((r for r in rows if r[0] == status), key=lambda r: r[2].lower())
        if not group:
            continue
        parts.append(f"\n## {status} ({len(group)})\n\n")
        for _, date, rel, title, note in group:
            tail = f" — {note}" if note else ""
            parts.append(f"- {date or '—'} — [{title}]({rel}){tail}\n")
    return "".join(parts)


def unindexable(rows: list[tuple[str, str, str, str, str]]) -> list[tuple[str, str, str]]:
    """(status, path, problem) for every record this generator cannot index.

    A record whose ``status`` is not one of STATUSES used to be dropped from the
    index entirely: it rendered under no heading, nothing failed, and the file
    was invisible to every reader who starts at ``tasks/_index.md``. Nine records
    were in that state on 2026-10-25, including the remediation plan that was
    being executed at the time. A missing ``date`` is reported the same way for
    less severe reasons -- the record still indexes, but with a placeholder.
    """
    found: list[tuple[str, str, str]] = []
    for status, date, rel, _title, _note in rows:
        if status not in STATUSES:
            found.append((status, rel, f"status {status!r} is not one of {', '.join(STATUSES)}"))
        elif not date:
            found.append((status, rel, "no frontmatter date"))
    return found


def main() -> int:
    rows = records()
    stray = unindexable(rows)
    if stray:
        print("Records this index cannot place (fix the frontmatter, then rerun):")
        for status, rel, problem in stray:
            print(f"  {rel}: {problem} (status={status!r})")
        print(
            "Every record needs `status:` (open | superseded | done | reference) and "
            "`date:` in its frontmatter."
        )
        return 1
    new = render(rows)
    if "--check" in sys.argv:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current.replace("\r\n", "\n") != new:
            print("tasks/_index.md is out of date: run python scripts/gen_tasks_index.py")
            return 1
        return 0
    INDEX.write_text(new, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
